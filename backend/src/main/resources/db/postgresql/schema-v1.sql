-- Run once against the target PostgreSQL database before starting the API.
-- Keep schema changes in versioned SQL scripts; Hibernate is configured to validate only.

CREATE TABLE APP_USER_ACCOUNT (
    USER_ID       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    DISPLAY_NAME  VARCHAR(100) NOT NULL,
    EMAIL         VARCHAR(320),
    PASSWORD_HASH VARCHAR(100),
    STATUS        VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    CREATED_AT    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_APP_USER_ACCOUNT PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_APP_USER_ACCOUNT_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_APP_USER_ACCOUNT_STATUS CHECK (STATUS IN ('ACTIVE', 'LOCKED', 'DELETED'))
);

CREATE TABLE APP_AUTH_IDENTITY (
    IDENTITY_ID      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    USER_ID          BIGINT NOT NULL,
    PROVIDER         VARCHAR(20) NOT NULL,
    PROVIDER_SUBJECT VARCHAR(255) NOT NULL,
    CREATED_AT       TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_APP_AUTH_IDENTITY PRIMARY KEY (IDENTITY_ID),
    CONSTRAINT FK_APP_AUTH_IDENTITY_USER FOREIGN KEY (USER_ID)
        REFERENCES APP_USER_ACCOUNT (USER_ID),
    CONSTRAINT UQ_APP_AUTH_PROVIDER_SUBJECT UNIQUE (PROVIDER, PROVIDER_SUBJECT),
    CONSTRAINT CK_APP_AUTH_PROVIDER CHECK (PROVIDER IN ('LOCAL', 'GOOGLE', 'KAKAO', 'NAVER'))
);

CREATE INDEX IX_APP_AUTH_IDENTITY_USER ON APP_AUTH_IDENTITY (USER_ID);
